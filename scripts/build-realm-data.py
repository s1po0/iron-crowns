#!/usr/bin/env python3
"""Original per-chunk terrain albedo/normal maps, streamed region containers.
No unused padding/duplicate payloads. Each texture belongs to a rendered 48 m chunk.
Use build/ for output: generated media must not be committed to Git.
"""
import argparse, hashlib, json, struct, tempfile, shutil
from pathlib import Path
import numpy as np
from PIL import Image
RES=1024
CHUNKS=25
REGION=5
MAGIC=b'ICREG002'
MAX_REGION=96*1024*1024

def noise(x,y,scale,seed):
    x=x/np.float32(scale); y=y/np.float32(scale)
    ix=np.floor(x).astype(np.uint32); iy=np.floor(y).astype(np.uint32)
    fx=x-np.floor(x); fy=y-np.floor(y); fx=fx*fx*(3-2*fx); fy=fy*fy*(3-2*fy)
    def h(a,b):
        v=a*np.uint32(374761393)+b*np.uint32(668265263)+np.uint32(seed)
        v=(v^(v>>np.uint32(13)))*np.uint32(1274126177)
        return ((v^(v>>np.uint32(16)))&np.uint32(0xffffff)).astype(np.float32)/np.float32(0xffffff)
    a=h(ix,iy); b=h(ix+np.uint32(1),iy); c=h(ix,iy+np.uint32(1)); d=h(ix+np.uint32(1),iy+np.uint32(1))
    return (a*(1-fx)+b*fx)*(1-fy)+(c*(1-fx)+d*fx)*fy

def tile(x,y,folder):
    # Global coordinates keep texture borders continuous between adjacent chunks.
    wx=(x*RES+np.arange(RES,dtype=np.float32)[None,:])*np.float32(48/RES)
    wy=(y*RES+np.arange(RES,dtype=np.float32)[:,None])*np.float32(48/RES)
    broad=noise(wx,wy,7,20261020)
    clumps=noise(wx,wy,.55,1027)
    grit=noise(wx,wy,.055,9017)
    soil=np.clip((broad-.42)*3+clumps*.25,0,1)
    pebbles=np.clip((noise(wx,wy,.16,501)-.55)*3,0,1)**2
    blades=(np.maximum(0,np.sin(wx*47+clumps*8)*np.cos(wy*13+clumps*4))**8)*(1-soil)
    height=(grit-.5)*.018+pebbles*.035+blades*.025+clumps*.01
    gy,gx=np.gradient(height,np.float32(48/RES))
    norm=np.sqrt(gx*gx+gy*gy+1)
    normal=np.stack(((-gx/norm+1)*127.5,(gy/norm+1)*127.5,(1/norm+1)*127.5),axis=-1)
    grass=np.array([49,71,33],dtype=np.float32); earth=np.array([91,78,55],dtype=np.float32)
    color=grass[None,None,:]*(1-soil[:,:,None])+earth[None,None,:]*soil[:,:,None]
    detail=(grit-.5)*27+pebbles*27+blades*24+(clumps-.5)*13
    color+=detail[:,:,None]
    files=[]
    for kind,array in [('albedo',color),('normal',normal)]:
        p=folder/f'{x}_{y}_{kind}.png'
        Image.fromarray(np.clip(array,0,255).astype(np.uint8)).save(p,compress_level=6)
        files.append(p)
    return files

def sha(path):
    h=hashlib.sha256()
    with path.open('rb') as f:
        for data in iter(lambda:f.read(1024*1024),b''):h.update(data)
    return h.hexdigest()

def region(rx,ry,out,fixture=False):
    with tempfile.TemporaryDirectory(prefix='realm-',dir=out) as td:
        folder=Path(td); paths=[]
        for y in range(ry*REGION,min(CHUNKS,(ry+1)*REGION)):
            for x in range(rx*REGION,min(CHUNKS,(rx+1)*REGION)):
                if fixture:
                    for kind,rgb in [('albedo',(60+x,85+y,40)),('normal',(128,128,255))]:
                        p=folder/f'{x}_{y}_{kind}.png'; Image.new('RGB',(RES,RES),rgb).save(p);paths.append(p)
                else:paths.extend(tile(x,y,folder))
        entries=[{'name':p.name,'bytes':p.stat().st_size,'sha256':sha(p)} for p in paths]
        manifest={'api':2,'world':'realm-400-v1','revision':1,'region':[rx,ry],'resolution':RES,'files':entries}
        header=json.dumps(manifest,sort_keys=True,separators=(',',':')).encode()
        path=out/f'Realm-Region-{rx}-{ry}.icregion'
        with path.open('wb') as target:
            target.write(MAGIC+struct.pack('<I',len(header))+header)
            for p in paths:
                with p.open('rb') as f:shutil.copyfileobj(f,target,65536)
        assert path.stat().st_size<=MAX_REGION, 'Region exceeds bounded importer budget'
        result={'file':path.name,'bytes':path.stat().st_size,'sha256':sha(path),'region':[rx,ry]}
        print(json.dumps(result),flush=True)
        return result

def main():
    ap=argparse.ArgumentParser();ap.add_argument('output',type=Path);ap.add_argument('--region',nargs=2,type=int);ap.add_argument('--sample-tile',action='store_true');ap.add_argument('--test-fixture',action='store_true')
    a=ap.parse_args();a.output.mkdir(parents=True,exist_ok=True)
    if a.sample_tile:
        for p in tile(12,12,a.output):print(p,p.stat().st_size)
        return
    ids=[tuple(a.region)] if a.region else [(x,y) for y in range(5) for x in range(5)]
    rows=[]
    for x,y in ids:
        assert 0<=x<5 and 0<=y<5
        rows.append(region(x,y,a.output,a.test_fixture))
    total=sum(r['bytes'] for r in rows)
    catalog={'schema':1,'world':'realm-400-v1','grid':[400,400],'chunk_cells':16,'texture_resolution':RES,'regions':rows,'total_bytes':total,'test_fixture':a.test_fixture,'provenance':'Original procedural terrain albedo and tangent-space normals generated by scripts/build-realm-data.py. No external proprietary media, padding or embedded code.'}
    (a.output/'realm-manifest.json').write_text(json.dumps(catalog,indent=2)+'\n')
    (a.output/'SHA256SUMS.txt').write_text(''.join(f"{r['sha256']}  {r['file']}\n" for r in rows))
    print(f'REALM_DATA_COMPLETE: {total} bytes, {len(rows)} regions',flush=True)
if __name__=='__main__':main()
